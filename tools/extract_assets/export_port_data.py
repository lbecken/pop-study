#!/usr/bin/env python3
"""Generate the data files the C port needs from the original source.

New code for the pop-study project.  Output is derived from the original
Prince of Persia source and is written to a build directory, never committed.

Usage:
    python3 tools/extract_assets/export_port_data.py \
        --source /path/to/Prince-of-Persia-Apple-II --out build/data

Output:
    seqtable.bin      assembled SEQTABLE.S with a 16-byte header
                      (layout: modern-port/src/assets/pop_assets.h)
    pop_seqnames.h    #define POP_SEQNO_<NAME> <n> for every sequence name
                      in SEQDATA.S
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from merlin_data import assemble, parse_equates  # noqa: E402
from pop_animdata import decode_sequence_table  # noqa: E402

SRC = os.path.join("01 POP Source", "Source")
MAGIC = b"POPSEQT1"
NOT_SEQUENCES = ("fcheckmark", "fcentermark")


def build_seqtable(source):
    with open(os.path.join(source, SRC, "SEQTABLE.S"), encoding="ascii") as f:
        asm = assemble(f.read())
    table = decode_sequence_table(asm)
    if table.problems:
        raise SystemExit("sequence table failed its structural checks:\n  "
                         + "\n  ".join(table.problems))
    data = asm.image[:table.end - asm.origin]
    header = MAGIC + struct.pack("<HHHH", asm.origin, len(data), len(table.entries), 0)
    return header + data, len(table.entries)


def build_names(source, entry_count):
    with open(os.path.join(source, SRC, "SEQDATA.S"), encoding="ascii") as f:
        eq = parse_equates(f.read())
    names = {k: v for k, v in eq.items() if v > 0 and k not in NOT_SEQUENCES}
    seen = {}
    lines = [
        "/* Generated by tools/extract_assets/export_port_data.py from SEQDATA.S.",
        " * Derived from the original source; do not commit. */",
        "#ifndef POP_SEQNAMES_H",
        "#define POP_SEQNAMES_H",
        "",
        "#define POP_SEQ_ENTRY_COUNT %d" % entry_count,
        "",
    ]
    for name, value in sorted(names.items(), key=lambda kv: (kv[1], kv[0])):
        macro = "POP_SEQNO_" + name.upper()
        if macro in seen:
            raise SystemExit("name collision: %s and %s" % (name, seen[macro]))
        if value > entry_count:
            raise SystemExit("%s = %d is beyond the entry table" % (name, value))
        seen[macro] = name
        lines.append("#define %-28s %3d  /* %s */" % (macro, value, name))
    lines += ["", "#endif /* POP_SEQNAMES_H */", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", default=os.path.join("build", "data"))
    args = ap.parse_args(argv)
    if not os.path.isdir(os.path.join(args.source, SRC)):
        ap.error("not found: %s" % os.path.join(args.source, SRC))
    blob, entries = build_seqtable(args.source)
    header = build_names(args.source, entries)
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "seqtable.bin"), "wb") as f:
        f.write(blob)
    with open(os.path.join(args.out, "pop_seqnames.h"), "w") as f:
        f.write(header)
    print("wrote %s: seqtable.bin (%d bytes, %d entries), pop_seqnames.h"
          % (args.out, len(blob), entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
