#!/usr/bin/env python3
"""Generate the data files the C port needs from the original source.

New code for the pop-study project.  Output is derived from the original
Prince of Persia source and is written to a build directory, never committed.

Usage:
    python3 tools/extract_assets/export_port_data.py \
        --source /path/to/Prince-of-Persia-Apple-II --out build/data

Output:
    seqtable.bin      assembled SEQTABLE.S with a 16-byte header
                      (layout: modern-port/src/assets/pop_assets.h)
    pop_seqnames.h    #define POP_SEQNO_<NAME> <n> for every sequence name
                      in SEQDATA.S
    sfx.bin           speaker toggle list of every sound effect, obtained by
                      executing SOUND.S (layout: pop_assets.h)
    pop_sfxnames.h    #define POP_SFX_<NAME> <n> for every effect name
    framedef.bin      assembled FRAMEDEF.S with a 24-byte header
    autodata.bin      AUTO.S tables: fight parameters per opponent type and
                      level, the shadow's scripted positions and movement
    imgdims.bin       width and height of every character image, by table,
                      with the four alternative opponent sets (no image data)
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "extract_audio"))

from merlin_data import assemble, parse_equates  # noqa: E402
from pop_animdata import decode_sequence_table  # noqa: E402
from pop_imgtable import parse_image_table  # noqa: E402
from pop_sfx import CPU_HZ, SoundModule  # noqa: E402

SRC = os.path.join("01 POP Source", "Source")
MAGIC = b"POPSEQT1"
NOT_SEQUENCES = ("fcheckmark", "fcentermark")


def build_seqtable(source):
    with open(os.path.join(source, SRC, "SEQTABLE.S"), encoding="ascii") as f:
        asm = assemble(f.read())
    table = decode_sequence_table(asm)
    if table.problems:
        raise SystemExit("sequence table failed its structural checks:\n  "
                         + "\n  ".join(table.problems))
    data = asm.image[:table.end - asm.origin]
    header = MAGIC + struct.pack("<HHHH", asm.origin, len(data), len(table.entries), 0)
    return header + data, len(table.entries)


def build_names(source, entry_count):
    with open(os.path.join(source, SRC, "SEQDATA.S"), encoding="ascii") as f:
        eq = parse_equates(f.read())
    names = {k: v for k, v in eq.items() if v > 0 and k not in NOT_SEQUENCES}
    seen = {}
    lines = [
        "/* Generated by tools/extract_assets/export_port_data.py from SEQDATA.S.",
        " * Derived from the original source; do not commit. */",
        "#ifndef POP_SEQNAMES_H",
        "#define POP_SEQNAMES_H",
        "",
        "#define POP_SEQ_ENTRY_COUNT %d" % entry_count,
        "",
    ]
    for name, value in sorted(names.items(), key=lambda kv: (kv[1], kv[0])):
        macro = "POP_SEQNO_" + name.upper()
        if macro in seen:
            raise SystemExit("name collision: %s and %s" % (name, seen[macro]))
        if value > entry_count:
            raise SystemExit("%s = %d is beyond the entry table" % (name, value))
        seen[macro] = name
        lines.append("#define %-28s %3d  /* %s */" % (macro, value, name))
    lines += ["", "#endif /* POP_SEQNAMES_H */", ""]
    return "\n".join(lines)


def build_framedef(source):
    with open(os.path.join(source, SRC, "FRAMEDEF.S"), encoding="ascii") as f:
        asm = assemble(f.read())
    sym = asm.symbols
    header = b"POPFRAM1" + struct.pack(
        "<HHHHHHHH", asm.origin, len(asm.image), sym["Fdef"], sym["altset1"],
        sym["altset2"], sym["swordtab"], 0, 0)
    return header + asm.image


# Character table number (as computed by decodeim, CTRLSUBS.S 1017-1039, and
# indexed into chtablist, GRAFIX.S 186-187) -> image file.  Table 3 is the
# opponent set, which the game swaps per level.  The five opponent files have
# 32 images each but different sizes image for image, so all five are
# exported: the guard set in position 3 and the others after the seven.
CHTABLE_FILES = ("IMG.CHTAB1", "IMG.CHTAB2", "IMG.CHTAB3", "IMG.CHTAB4.GD", "IMG.CHTAB5",
                 "IMG.CHTAB6.A", "IMG.CHTAB7")
OPPONENT_VARIANTS = ("IMG.CHTAB4.FAT", "IMG.CHTAB4.SHAD", "IMG.CHTAB4.SKEL",
                     "IMG.CHTAB4.VIZ")


def image_dims(source, files=CHTABLE_FILES):
    """[(width bytes, height lines), ...] for each character table."""
    tables = []
    for name in files:
        with open(os.path.join(source, "01 POP Source", "Images", name), "rb") as f:
            table = parse_image_table(f.read())
        tables.append([(im.width_bytes, im.height) for im in table.images])
    return tables


def build_imgdims(source):
    tables = image_dims(source, CHTABLE_FILES + OPPONENT_VARIANTS)
    blob = b"POPIDIM1" + struct.pack("<HH", len(tables), 0)
    for dims in tables:
        blob += struct.pack("<H", len(dims))
        for w, h in dims:
            blob += bytes((w, h))
    return blob


# AUTO.S tables that describe content: label, length.  The first ten are
# contiguous in memory and are exported as one block, because the original
# indexes across their ends.
AUTO_FIGHT = (("strikeprob", 12), ("restrikeprob", 12), ("blockprob", 12),
              ("impblockprob", 12), ("advprob", 12), ("refractimer", 12),
              ("specialcolor", 12), ("extrastrength", 12), ("basicstrength", 14),
              ("basiccolor", 14))
AUTO_SHADPOS = (("shadpos6a", 8), ("shadpos5", 8), ("shadpos12", 8))


def build_autodata(source):
    """Fight parameters, the shadow's scripted positions and its level-5
    movement script, cut out of the assembled AUTO.S."""
    from mos6502 import assemble_6502
    from pop_sfx import include_resolver
    src = os.path.join(source, SRC)
    with open(os.path.join(src, "AUTO.S"), encoding="ascii") as f:
        asm = assemble_6502(f.read(), include_resolver(
            src, os.path.join(source, "02 POP Disk Routines", "CP.525")))
    sym = asm.symbols

    def block(tables):
        at = sym[tables[0][0]]
        for name, size in tables:                    # contiguous, in this order
            if sym[name] != at:
                raise SystemExit("AUTO.S: %s is not where expected" % name)
            at += size
        return asm.image[sym[tables[0][0]] - asm.origin:at - asm.origin]

    fight = block(AUTO_FIGHT)
    shadpos = block(AUTO_SHADPOS)
    start = sym["ShadProg5"] - asm.origin
    prog = bytearray()
    while True:                                      # (frame, command) pairs up to EndProg
        prog += asm.image[start + len(prog):start + len(prog) + 2]
        if prog[-1] in (0xFE, 0xFF) or len(prog) > 254:
            break
    # the demo level's script for the kid is in SUBS.S, in the same format
    with open(os.path.join(src, "SUBS.S"), encoding="ascii") as f:
        subs = assemble_6502(f.read(), include_resolver(
            src, os.path.join(source, "02 POP Disk Routines", "CP.525")))
    start = subs.symbols["DemoProg1"] - subs.origin
    demo = bytearray()
    while True:
        demo += subs.image[start + len(demo):start + len(demo) + 2]
        if demo[-1] in (0xFE, 0xFF) or len(demo) > 254:
            break
    return (b"POPAUTO1" + struct.pack("<HHHH", len(fight), len(shadpos), len(prog), len(demo))
            + fight + shadpos + bytes(prog) + bytes(demo))


def build_sfx(source):
    mod = SoundModule(os.path.join(source, SRC))
    effects = mod.all_effects()
    blob = b"POPSFX01" + struct.pack("<IHH", CPU_HZ, len(effects), 0)
    for e in effects:
        blob += struct.pack("<II", e.total_cycles, len(e.toggles))
        blob += struct.pack("<%dI" % len(e.toggles), *e.toggles)
    lines = [
        "/* Generated by tools/extract_assets/export_port_data.py from SOUNDNAMES.S.",
        " * Derived from the original source; do not commit. */",
        "#ifndef POP_SFXNAMES_H",
        "#define POP_SFXNAMES_H",
        "",
        "#define POP_SFX_ENTRY_COUNT %d" % len(effects),
        "",
    ]
    for e in effects:
        lines.append("#define %-24s %2d" % ("POP_SFX_" + e.name.upper(), e.number))
    lines += ["", "#endif /* POP_SFXNAMES_H */", ""]
    return blob, "\n".join(lines), len(effects)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", default=os.path.join("build", "data"))
    args = ap.parse_args(argv)
    if not os.path.isdir(os.path.join(args.source, SRC)):
        ap.error("not found: %s" % os.path.join(args.source, SRC))
    blob, entries = build_seqtable(args.source)
    header = build_names(args.source, entries)
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "seqtable.bin"), "wb") as f:
        f.write(blob)
    with open(os.path.join(args.out, "pop_seqnames.h"), "w") as f:
        f.write(header)
    sfx, sfx_header, sfx_count = build_sfx(args.source)
    with open(os.path.join(args.out, "sfx.bin"), "wb") as f:
        f.write(sfx)
    with open(os.path.join(args.out, "pop_sfxnames.h"), "w") as f:
        f.write(sfx_header)
    frames = build_framedef(args.source)
    with open(os.path.join(args.out, "framedef.bin"), "wb") as f:
        f.write(frames)
    with open(os.path.join(args.out, "autodata.bin"), "wb") as f:
        f.write(build_autodata(args.source))
    dims = build_imgdims(args.source)
    with open(os.path.join(args.out, "imgdims.bin"), "wb") as f:
        f.write(dims)
    print("wrote %s: seqtable.bin (%d bytes, %d entries), pop_seqnames.h, "
          "sfx.bin (%d bytes, %d effects), pop_sfxnames.h, framedef.bin (%d bytes), "
          "imgdims.bin (%d bytes)"
          % (args.out, len(blob), entries, len(sfx), sfx_count, len(frames), len(dims)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
